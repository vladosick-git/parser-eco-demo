_ADJ_ENDINGS = ("ая", "ой", "ую", "ий", "ого", "ом", "ему")


def _stem(word: str) -> str:
    for ending in sorted(_ADJ_ENDINGS, key=len, reverse=True):
        if word.endswith(ending):
            return word[: -len(ending)]
    return word


# «брянск» -> «32», «алтайск» (край) -> «22» и т.п.
_OBLAST_STEMS = {
    _stem(name.split()[0].lower()): code
    for code, name in REGIONS.items()
    if name.endswith(("область", "край"))
}


def _prep(text: str) -> str:
    return " " + re.sub(r"\s+", " ", text.lower().replace("ё", "е")) + " "


def _has_word(haystack: str, needle: str) -> bool:
    return re.search(r"(?<![\w-])" + re.escape(needle) + r"(?![\w-])", haystack) is not None


def match_region(text: str | None) -> str | None:
    """Код субъекта по свободному тексту («Брянская обл., Почепский р-н», «Москва») или None."""
    if not text:
        return None
    t = _prep(text)
    # 1. «...ская область», «...ский край»
    for m in re.finditer(r"([а-я-]+)\s+(обл|област|кра[йяею])", t):
        code = _OBLAST_STEMS.get(_stem(m.group(1)))
        if code:
            return code
    # 2. республики и автономные округа
    for key, code in _KEYWORDS.items():
        if re.search(r"(?<![\w-])" + re.escape(key), t):
            return code
    # 3. города (длинные названия раньше коротких, чтобы «нижний новгород» не стал «новгородом»)
    for city in sorted(_CITIES, key=len, reverse=True):
        if _has_word(t, city):
            return _CITIES[city]
    return None


def region_from_kpp(kpp: str | None) -> str | None:
    """Первые две цифры КПП (код налогового органа) -> код субъекта, если он есть в справочнике."""
    if kpp and len(kpp) >= 2 and kpp[:2] in REGIONS:
        return kpp[:2]
    return None


def region_name(code: str | None) -> str | None:
    return REGIONS.get(code) if code else None
